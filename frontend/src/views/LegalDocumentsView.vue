import { useRoute, useRouter } from "vue-router";

const SITE_NAME = "ИЖС";

const route = useRoute();
const router = useRouter();

const tabMap = {
  privacy: "privacy",
  terms: "terms",
  access: "access",
  cooperation: "cooperation",
  owner: "owner",
};

const allowedTabs = Object.keys(tabMap);

function normalizeTab(value) {
  const raw = String(value || "")
    .trim()
    .toLowerCase();
  return allowedTabs.includes(raw) ? raw : "privacy";
}

const activeTab = ref(normalizeTab(route.query.tab));

watch(
  () => route.query.tab,
  (tab) => {
    activeTab.value = normalizeTab(tab);
  },
);

watch(activeTab, (tab) => {
  const normalized = normalizeTab(tab);
  if (route.query.tab === normalized) return;
  router.replace({ path: "/legal", query: { tab: normalized } });
});

const titleByTab = computed(() => {
  if (activeTab.value === "privacy") return "Политика конфиденциальности";
  if (activeTab.value === "terms") {
    return `Пользовательское соглашение. Доступ к сервисам ${SITE_NAME}`;
