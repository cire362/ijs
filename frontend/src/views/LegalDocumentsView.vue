  if (activeTab.value === "cooperation") {
    return `Публичные условия сотрудничества с ${SITE_NAME}`;
  }
  if (activeTab.value === "owner") {
    return `Информация о правообладателе ${SITE_NAME}`;
  }
  return `Пользовательское соглашение. Доступ к сервисам ${SITE_NAME}`;
});
